type ContactInput = Omit<PropertyGroup['contacts'][number], 'id' | 'propertyGroupId'>;

const withContacts = (
  base: Omit<PropertyGroup, 'contacts' | 'id'> & { contacts: ContactInput[] },
): PropertyGroup => {
  const id = nanoid();
  return {
    id,
    ...base,
    contacts: base.contacts.map((contact) => ({
      id: nanoid(),
      propertyGroupId: id,
      ...contact,
    })),
  };
};

